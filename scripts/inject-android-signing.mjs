#!/usr/bin/env node
/**
 * Injects the Android release signing config into a prebuilt `android/` tree,
 * the same way `eas build` does. Reads the upload keystore + passwords from a
 * JSON file (path via SIGNING_JSON, default <workspace>/.signing.json) written
 * by the Jenkins release pipeline from the `android-upload-keystore` credential.
 *
 * It writes `android/app/ci-signing.gradle` and appends an `apply from:` line to
 * `android/app/build.gradle`. No EAS account or eas-cli is involved.
 *
 * Keystore file resolution: `keystorePath` in the JSON if present, else the
 * sibling `<workspace>/.signing/upload.jks` written by the pipeline.
 */
import fs from "node:fs";
import path from "node:path";

const workspace = process.env.WORKSPACE || process.cwd();
const signingJson = process.env.SIGNING_JSON || path.join(workspace, ".signing.json");

let creds;
try {
  creds = JSON.parse(fs.readFileSync(signingJson, "utf8"));
} catch (e) {
  console.error(`[signing] cannot read ${signingJson}: ${e.code ?? e.message}`);
  process.exit(1);
}
const keystorePath =
  creds.keystorePath || path.join(workspace, ".signing", "upload.jks");

if (!fs.existsSync(keystorePath)) {
  console.error(`[signing] keystore not found: ${keystorePath}`);
  process.exit(1);
}

const androidAppDir = path.join(workspace, "android", "app");
const buildGradlePath = path.join(androidAppDir, "build.gradle");

const storePassword = creds.keystorePassword;
const keyPassword = creds.keyPassword || creds.keystorePassword;
const keyAlias = creds.keyAlias;

const gradle = `// Generated by scripts/inject-android-signing.mjs (CI release signing).
// Equivalent to eas-build-inject-android-credentials.gradle.
android {
  signingConfigs {
    release {
      storeFile file(${JSON.stringify(keystorePath)})
      storePassword ${JSON.stringify(storePassword)}
      keyAlias ${JSON.stringify(keyAlias)}
      keyPassword ${JSON.stringify(keyPassword)}
    }
  }
  buildTypes {
    release { signingConfig android.signingConfigs.release }
  }
}
`;

// Contains the keystore passwords in clear text: owner-only, never world-readable.
fs.writeFileSync(path.join(androidAppDir, "ci-signing.gradle"), gradle, { mode: 0o600 });

let buildGradle;
try {
  buildGradle = fs.readFileSync(buildGradlePath, "utf8");
} catch (e) {
  console.error(`[signing] cannot read ${buildGradlePath} (run expo prebuild first): ${e.code ?? e.message}`);
  process.exit(1);
}
if (!buildGradle.includes("ci-signing.gradle")) {
  buildGradle += "\napply from: \"./ci-signing.gradle\"\n";
  fs.writeFileSync(buildGradlePath, buildGradle);
}

console.log(`[signing] injected release signing config (alias ${keyAlias})`);
