const fs = require("fs");
const path = require("path");

const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withXcodeProject,
} = require("expo/config-plugins");

const { XcodeUtils } = IOSConfig;

const CLASS_NAME = "AnimuFeatureFlags";
const HEADER_FILE_NAME = `${CLASS_NAME}.h`;
const SOURCE_FILE_NAME = `${CLASS_NAME}.mm`;

/** Where the call goes in AppDelegate: right after the factory exists. */
const FACTORY_LINE = "let factory = ExpoReactNativeFactory(delegate: delegate)";
const APPLY_CALL = `${CLASS_NAME}.apply()`;

const HEADER_SOURCE = `#import <Foundation/Foundation.h>

NS_ASSUME_NONNULL_BEGIN

/**
 * React Native feature flags the app turns on beyond the stable release level.
 * GENERATED by plugins/withIOSViewFilters.js — edit the plugin, not this file.
 */
@interface ${CLASS_NAME} : NSObject

/** Call once the React Native factory exists, before React Native starts. */
+ (void)apply;

@end

NS_ASSUME_NONNULL_END
`;

const IMPLEMENTATION_SOURCE = `#import "${HEADER_FILE_NAME}"

#import <react/featureflags/ReactNativeFeatureFlags.h>
#import <react/featureflags/ReactNativeFeatureFlagsOverridesOSSStable.h>

using namespace facebook::react;

namespace {

/**
 * The stable release level's flags (what the factory installed), plus
 * SwiftUI-backed view filters: without them iOS ignores \`filter: [{ blur }]\`
 * (the lyrics' depth blur), which Android renders natively.
 */
class AnimuFeatureFlagsProvider : public ReactNativeFeatureFlagsOverridesOSSStable {
 public:
  bool enableSwiftUIBasedFilters() override
  {
    return true;
  }
};

} // namespace

/** GENERATED by plugins/withIOSViewFilters.js — edit the plugin, not this file. */
@implementation ${CLASS_NAME}

+ (void)apply
{
  // The factory has installed the stable flags (init); React Native has not
  // started yet, so no other thread reads them while they are replaced. Flags
  // already read keep their value: the provider extends the stable one.
  ReactNativeFeatureFlags::dangerouslyForceOverride(std::make_unique<AnimuFeatureFlagsProvider>());
}

@end
`;

/** AppDelegate with the flags applied after the factory is created (idempotent). */
function addApplyCall(contents) {
  if (contents.includes(APPLY_CALL)) return contents;
  if (!contents.includes(FACTORY_LINE)) {
    throw new Error(`withIOSViewFilters: AppDelegate no longer contains "${FACTORY_LINE}"`);
  }
  return contents.replace(FACTORY_LINE, (line) => {
    const indent = contents.slice(contents.lastIndexOf("\n", contents.indexOf(line)) + 1).match(/^\s*/)[0];
    return `${line}\n${indent}${APPLY_CALL}`;
  });
}

/** The bridging header with the class exposed to Swift (idempotent). */
function addBridgingImport(contents) {
  const line = `#import "${HEADER_FILE_NAME}"`;
  if (contents.includes(line)) return contents;
  return `${contents.trimEnd()}\n\n${line}\n`;
}

function withSourceFiles(config) {
  return withXcodeProject(config, (config) => {
    const projectRoot = config.modRequest.projectRoot;
    const projectName = XcodeUtils.getProjectName(projectRoot);
    const appDir = path.join(projectRoot, "ios", projectName);
    fs.mkdirSync(appDir, { recursive: true });
    fs.writeFileSync(path.join(appDir, HEADER_FILE_NAME), HEADER_SOURCE);
    fs.writeFileSync(path.join(appDir, SOURCE_FILE_NAME), IMPLEMENTATION_SOURCE);

    // Both skip a file already in the group (repeated, non-clean prebuilds).
    const project = config.modResults;
    XcodeUtils.addBuildSourceFileToGroup({
      filepath: `${projectName}/${SOURCE_FILE_NAME}`,
      groupName: projectName,
      project,
    });
    XcodeUtils.addFileToGroupAndLink({
      filepath: `${projectName}/${HEADER_FILE_NAME}`,
      groupName: projectName,
      project,
      addFileToProject: ({ project, file }) => project.addToPbxFileReferenceSection(file),
    });
    return config;
  });
}

function readIfPresent(file) {
  try {
    return fs.readFileSync(file, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return "";
    throw error;
  }
}

function withBridgingHeader(config) {
  return withDangerousMod(config, [
    "ios",
    (config) => {
      const projectRoot = config.modRequest.projectRoot;
      const projectName = XcodeUtils.getProjectName(projectRoot);
      const header = path.join(projectRoot, "ios", projectName, `${projectName}-Bridging-Header.h`);
      fs.writeFileSync(header, addBridgingImport(readIfPresent(header)));
      return config;
    },
  ]);
}

module.exports = function withIOSViewFilters(config) {
  config = withSourceFiles(config);
  config = withBridgingHeader(config);
  return withAppDelegate(config, (config) => {
    if (config.modResults.language !== "swift") {
      throw new Error("withIOSViewFilters: expected a Swift AppDelegate");
    }
    config.modResults.contents = addApplyCall(config.modResults.contents);
    return config;
  });
};

module.exports.addApplyCall = addApplyCall;
module.exports.addBridgingImport = addBridgingImport;
module.exports.IMPLEMENTATION_SOURCE = IMPLEMENTATION_SOURCE;
